-- lets the VEX rule recommendation daemon pick one open vuln per signature with an
-- index-only scan instead of reading every duplicate row of a signature from the heap.
CREATE INDEX IF NOT EXISTS idx_dependency_vulns_open_signature_id ON public.dependency_vulns (signature, id) WHERE state = 'open';
